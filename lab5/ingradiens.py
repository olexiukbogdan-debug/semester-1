import random  # бібліотека random потрібна, щоб вибирати випадковий інгредієнт

# список з 20 "походжень" (родовий відмінок, щоб підходило до будь-якого слова)
ORIGINS = ["Місяця", "Сонця", "Дракона", "Вовка", "Лісу", "Грому", "Туману",  # перша частина списку походжень
           "Попелу", "Льоду", "Вогню", "Ворона", "Змії", "Болота", "Гір",  # друга частина списку
           "Моря", "Ночі", "Зорі", "Пустелі", "Вітру", "Грози"]  # третя частина списку

# список з 10 типів інгредієнтів, 10 типів x 20 походжень = 200 різних інгредієнтів
TYPES = ["Корінь", "Листок", "Гриб", "Квітка", "Ягода",  # перша частина списку типів
         "Кристал", "Луска", "Перо", "Насіння", "Мох"]  # друга частина списку типів


def create_ingredient_pool():  # функція, що створює список усіх 200 інгредієнтів
    pool = []  # порожній список, у який складемо всі інгредієнти
    try:  # блок try: пробуємо виконати код, а якщо буде помилка - перейдемо в except
        for t in TYPES:  # перебираємо кожен тип інгредієнта
            for origin in ORIGINS:  # для кожного типу перебираємо кожне походження
                pool.append(t + " " + origin)  # склеюємо тип і походження (наприклад "Корінь Дракона") і додаємо в список
    except Exception as e:  # якщо сталась помилка - ловимо її в змінну e
        print("Помилка створення пулу інгредієнтів:", e)  # виводимо повідомлення про помилку
    return pool  # повертаємо готовий список інгредієнтів


def random_ingredient(pool):  # функція, що вибирає один випадковий інгредієнт зі списку
    try:  # пробуємо виконати код
        return random.choice(pool)  # random.choice бере випадковий елемент списку і ми його повертаємо
    except Exception as e:  # якщо сталась помилка (наприклад, список порожній)
        print("Помилка вибору інгредієнта:", e)  # виводимо повідомлення про помилку
        return None  # повертаємо None, тобто "нічого"


def get_type(name):  # функція, що з назви інгредієнта дістає його тип
    try:  # пробуємо виконати код
        return name.split(" ")[0]  # ділимо назву по пробілу і беремо перше слово (це і є тип)
    except Exception as e:  # якщо сталась помилка
        print("Помилка визначення типу:", e)  # виводимо повідомлення про помилку
        return ""  # повертаємо порожній рядок